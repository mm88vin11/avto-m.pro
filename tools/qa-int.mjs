// Интерактив на телефоне: фильтры в шторке, подбор, «мой автомобиль», список запроса, сравнение, проверка совместимости в карточке.
import { createRequire } from 'module';
import fs from 'fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const base = process.argv[2] || 'http://localhost:8080', out = process.argv[3] || 'qa-shots';
fs.mkdirSync(out, { recursive: true });
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
await ctx.addCookies([{ name: 'avtom_consent', value: 'necessary', url: base }]);
const p = await ctx.newPage(); const errs = [];
p.on('pageerror', e => errs.push(String(e))); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto(base + '/catalog');
await p.click('.filters-open'); await p.waitForTimeout(700);
await p.selectOption('#fc-make', 'ford'); await p.waitForTimeout(100);
await p.selectOption('#fc-model', 'focus-ii'); await p.waitForTimeout(100);
await p.selectOption('#fc-body', 'Седан'); await p.waitForTimeout(600);
console.log('кнопка шторки:', await p.textContent('[data-apply]'));
await p.screenshot({ path: out + '/int-filters.png' });
await p.click('[data-apply]'); await p.waitForTimeout(900);
console.log('адрес:', decodeURIComponent(p.url()), '·', await p.textContent('.found'));
console.log('«мой автомобиль»:', await p.locator('[data-garage] span').first().textContent().catch(() => '—'));
await p.screenshot({ path: out + '/int-results.png', fullPage: true });
await p.locator('[data-cart]').first().click(); await p.waitForTimeout(300);
await p.goto(base + '/catalog/rasshiritelnye-bachki');
await p.locator('[data-cart]').first().click();
await p.locator('[data-compare]').nth(0).click(); await p.locator('[data-compare]').nth(1).click();
console.log('бейдж запроса:', await p.locator('.tabbar [data-count=cart]').textContent());
await p.goto(base + '/cart'); await p.waitForSelector('.ci');
console.log('в списке:', await p.locator('.ci').count(), '·', await p.textContent('[data-cart-sum]'));
await p.screenshot({ path: out + '/int-cart.png', fullPage: true });
await p.goto(base + '/compare'); await p.waitForSelector('.cmp');
await p.screenshot({ path: out + '/int-compare.png', fullPage: true });
await p.goto(base + '/product/gazovye-upory-bagazhnika-liftautopro-dlya-ford-focus-ii-universal-lap-10375');
await p.waitForTimeout(300);
console.log('совместимость в карточке (машина из подбора — седан):', await p.locator('[data-fitbox]').getAttribute('data-state'));
await p.screenshot({ path: out + '/int-fit.png' });
await p.goto(base + '/'); await p.fill('#q', 'фокус 2 универ'); await p.waitForTimeout(700);
console.log('подсказки поиска:', await p.locator('.sg-item').count());
await p.screenshot({ path: out + '/int-suggest.png' });
console.log('ошибки:', errs.length ? errs : 'нет');
await b.close();
